export function translateShared(key, t, language, values = {}) {
  const contextTranslation = t(key);
  const translation =
    contextTranslation !== key
    ? contextTranslation
    : language === "hi"
      ? sharedComponents[key] || key
      : key;

  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, value),
    translation,
  );
}

export default sharedComponents;
